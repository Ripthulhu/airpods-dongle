// Relay metadata is accepted only for the two exact LibrePods ownership-loss schemas.
// shortcut: unknown dictionary variants remain passive until their wire schema is captured.
static inline bool aacp_route_hijack(const uint8_t *packet,size_t length,const uint8_t expected_other[6]) {
    if (!aacp_route_address_valid(expected_other) || !aacp_route_header(packet,length,0x11) || length<14 ||
        length>AACP_ROUTE_MAX_PACKET || (size_t)(packet[12]|(uint16_t)packet[13]<<8)!=length-14) return false;
    for (unsigned i=0;i<6;++i) if (packet[6+i]!=expected_other[5-i]) return false;
    return (length==sizeof(aacp_route_hijack_packet) &&
            !memcmp(packet+14,aacp_route_hijack_packet+14,length-14)) ||
           (length==sizeof(aacp_route_reverse_packet) &&
            !memcmp(packet+14,aacp_route_reverse_packet+14,length-14));
}
static inline size_t aacp_route_build(uint8_t *out,size_t capacity,aacp_route_kind_t kind,
                                     const uint8_t local[6],const uint8_t target[6]) {
    static const uint8_t own[]={4,0,4,0,9,0,6,1,0,0,0};
    const uint8_t *packet=NULL;size_t length=0,local_offset=0;
    switch (kind) {
        case AACP_ROUTE_OWN: packet=own;length=sizeof(own);break;
        case AACP_ROUTE_NEW_INFO: packet=aacp_route_new_info_packet;length=sizeof(aacp_route_new_info_packet);local_offset=63;break;
        case AACP_ROUTE_TIPI: packet=aacp_route_tipi_packet;length=sizeof(aacp_route_tipi_packet);local_offset=46;break;
        case AACP_ROUTE_MEDIA: packet=aacp_route_media_packet;length=sizeof(aacp_route_media_packet);local_offset=84;break;
        case AACP_ROUTE_HIJACK: packet=aacp_route_hijack_packet;length=sizeof(aacp_route_hijack_packet);break;
        case AACP_ROUTE_REVERSE: packet=aacp_route_reverse_packet;length=sizeof(aacp_route_reverse_packet);break;
        default: return 0;
    }
    if (!out || capacity<length || (kind!=AACP_ROUTE_OWN &&
        (!aacp_route_address_valid(local) || !aacp_route_address_valid(target) || !memcmp(local,target,6)))) return 0;
    memcpy(out,packet,length);
    if (kind!=AACP_ROUTE_OWN) for (unsigned i=0;i<6;++i) out[6+i]=target[5-i];
    if (local_offset) {
        static const char hex[]="0123456789ABCDEF";
        for (unsigned i=0;i<6;++i) {
            out[local_offset+3*i]=(uint8_t)hex[local[i]>>4];
            out[local_offset+3*i+1]=(uint8_t)hex[local[i]&15];
            if (i<5) out[local_offset+3*i+2]=':';
        }
    }
    return length;
}

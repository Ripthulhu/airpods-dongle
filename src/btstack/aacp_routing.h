#define AACP_ROUTE_MAX_PACKET 144u
typedef enum {
    AACP_ROUTE_OWN, AACP_ROUTE_NEW_INFO, AACP_ROUTE_TIPI,
    AACP_ROUTE_MEDIA, AACP_ROUTE_HIJACK, AACP_ROUTE_REVERSE
} aacp_route_kind_t;

static inline bool aacp_route_address_valid(const uint8_t address[6]) {
    if (!address) return false;
    unsigned nonzero=0,nonff=0;
    for (unsigned i=0;i<6;++i) { nonzero |= address[i]; nonff |= address[i]^0xffu; }
    return nonzero && nonff;
}
static inline bool aacp_route_header(const uint8_t *packet,size_t length,uint8_t opcode) {
    return packet && length>=6 && packet[0]==4 && packet[1]==0 && packet[2]==4 &&
        packet[3]==0 && packet[4]==opcode && packet[5]==0;
}
static inline bool aacp_route_ownership(const uint8_t *packet,size_t length,bool *owned) {
    if (!owned || !aacp_route_header(packet,length,9) || length!=11 || packet[6]!=6 ||
        packet[7]>2 || packet[8] || packet[9] || packet[10]) return false;
    *owned=packet[7]==1;
    return true;
}
static inline bool aacp_route_source(const uint8_t *packet,size_t length,uint8_t address[6],uint8_t *type) {
    if (!address || !type || !aacp_route_header(packet,length,0x0e) || length!=13 || packet[12]>2) return false;
    uint8_t decoded[6];
    for (unsigned i=0;i<6;++i) decoded[i]=packet[11-i];
    if (packet[12] && !aacp_route_address_valid(decoded)) return false;
    memcpy(address,decoded,6);*type=packet[12];
    return true;
}
// This two-host helper rejects ambiguous larger lists; count0 is valid but never proves ownership.
static inline bool aacp_route_devices(const uint8_t *packet,size_t length,const uint8_t local[6],
                                      uint8_t other[6],bool *sole_local) {
    if (!other || !sole_local || !aacp_route_address_valid(local) ||
        !aacp_route_header(packet,length,0x2e) || length<9 || packet[8]>2 || length!=9u+8u*packet[8]) return false;
    uint8_t found[6]={0};bool local_seen=false;
    for (unsigned i=0;i<packet[8];++i) {
        const uint8_t *address=packet+9+8*i; // Unlike source/relay, list entries use normal BD_ADDR order.
        if (!aacp_route_address_valid(address)) return false;
        if (!memcmp(address,local,6)) {
            if (local_seen) return false;
            local_seen=true;
        } else {
            if (aacp_route_address_valid(found)) return false;
            memcpy(found,address,6);
        }
    }
    memcpy(other,found,6);*sole_local=local_seen && packet[8]==1;
    return true;
}


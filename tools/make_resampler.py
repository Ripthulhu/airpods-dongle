#!/usr/bin/env python3
"""Generate the bounded float fractional-delay filters used by USB playback."""
import math
import pathlib

TAPS, PHASES = 33, 128


def generate():
    lines = ['// Generated by tools/make_resampler.py; no runtime coefficient generation.',
             '#ifndef AIRPODS_PLAYBACK_FILTER_H', '#define AIRPODS_PLAYBACK_FILTER_H',
             '#define PLAYBACK_FILTER_TAPS 33u', '#define PLAYBACK_FILTER_DELAY 16u',
             '#define PLAYBACK_FILTER_PHASES 128u',
             'static const float playback_filter[2][129][33] = {']
    for cutoff in (1.0, 10 / 11):
        lines.append(' {')
        for phase in range(PHASES + 1):
            coefficients = []
            for tap in range(TAPS):
                x = tap - (TAPS - 1) / 2 + phase / PHASES
                sinc = cutoff if abs(x) < 1e-12 else math.sin(math.pi * cutoff * x) / (math.pi * x)
                window = .42 - .5 * math.cos(2 * math.pi * tap / (TAPS - 1)) + .08 * math.cos(4 * math.pi * tap / (TAPS - 1))
                coefficients.append(sinc * window)
            total = sum(coefficients)
            lines.append('  {' + ','.join(f'{value / total:.9e}f' for value in coefficients) + '},')
        lines.append(' },')
    lines.extend(['};', '#endif', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    destination = pathlib.Path(__file__).resolve().parents[1] / 'src/btstack/playback_filter.h'
    destination.write_text(generate())
